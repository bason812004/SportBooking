import { z } from "zod";

const time = z.string().regex(/^(?:[01]\d|2[0-3]):00$/, "Gio phai la gio chan, vi du 06:00");
const flexTime = z.string().regex(/^(?:[01]\d|2[0-3]):[0-5]\d$/, "Gio khong hop le, vi du 06:30");
const optionalQuery = <T extends z.ZodTypeAny>(schema: T) =>
  z.preprocess((value) => value === "" ? undefined : value, schema.optional());
// IDs in this app are custom prefixed varchar (e.g. "c0001"), not real UUIDs — only payments.id is a genuine uuid.
const id = z.string().trim().min(1).max(40);

// Venue fields shared by the single-court form (courtWriteSchema) and venue registration (courtRegistrationSchema).
const courtVenueFields = z.object({
  name: z.string().min(2).max(180),
  description: z.string().optional(),
  // Since the 2025 administrative reform an address is street + ward/commune + province/city (no district).
  address: z.string().trim().min(5).max(255),
  ward: z.string().trim().min(2, "Vui long nhap Phuong/Xa").max(80),
  city: z.string().trim().min(2).max(80),
  latitude: z.number().optional(),
  longitude: z.number().optional(),
  openingTime: time,
  closingTime: time,
  depositPercent: z.coerce.number().min(0).max(49.99, "Cọc phải dưới 50%").optional().nullable()
});

export const courtWriteSchema = z.object({
  body: courtVenueFields.extend({
    categoryId: id,
    requireDeposit: z.boolean().optional()
  })
});

const surfaceNameKey = (name: string) => name.trim().replace(/\s+/g, " ").toLocaleLowerCase("vi");
const optionalSurfaceText = z.string().trim().max(120).nullish().transform((value) => value || null);

// Sub-courts declared at registration; their codes (S01...) are generated by the server, never taken from the client.
const registrationSport = z
  .object({
    categoryId: id,
    surfaces: z
      .array(z.object({ name: z.string().trim().min(1, "Ten san con khong duoc de trong").max(160), surface: optionalSurfaceText, size: optionalSurfaceText }))
      .min(1, "Moi mon can it nhat 1 san con")
      .max(30, "Toi da 30 san con moi mon")
  })
  .superRefine((sport, ctx) => {
    const seen = new Set<string>();
    sport.surfaces.forEach((surface, index) => {
      const key = surfaceNameKey(surface.name);
      if (seen.has(key)) ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["surfaces", index, "name"], message: "Ten san con bi trung trong cung mot mon" });
      seen.add(key);
    });
  });

// A venue with several sports becomes one court per sport (a court has one category and its own prices);
// the courts share the venue fields.
export const courtRegistrationSchema = z.object({
  body: courtVenueFields
    .extend({
      name: z.string().trim().min(2).max(150),
      sports: z.array(registrationSport).min(1, "Chon it nhat 1 mon").max(5, "Toi da 5 mon moi lan dang ky")
    })
    .superRefine((body, ctx) => {
      const seen = new Set<string>();
      body.sports.forEach((sport, index) => {
        if (seen.has(sport.categoryId)) ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["sports", index, "categoryId"], message: "Moi mon chi chon mot lan" });
        seen.add(sport.categoryId);
      });
    })
});

export type CourtRegistrationInput = z.infer<typeof courtRegistrationSchema>["body"];

